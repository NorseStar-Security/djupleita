/** Evidence-supported capabilities and explicit paths; no rule corpus or execution permission is inferred. */
import { digest } from './identity.ts'
import { MemoryError } from './errors.ts'
import { assetSignature, type MemoryState } from './state.ts'
import type { AssessmentCommand, AssetId, AttemptContext, MemoryEvent } from './schema.ts'

type Input<K extends AssessmentCommand['kind']> = Extract<AssessmentCommand, { kind: K }>
type Stored<K extends AssessmentCommand['kind']> = Input<K> & {
  revision: number
  assessmentId: string
  sessionId: string
  recordedAt: string
  evidenceId: string
}
type Capability = Stored<'capability'> & {
  assetSignatures: Record<string, string>
  supportAssetIds: AssetId[]
  requiredRevisions: Record<string, number>
}
type Path = Stored<'path'> & { capabilityRevisions: Record<string, number>; objectiveRevision: number }
interface EvaluationBudget { remaining: number; exhausted: boolean }
/** Graph records are reconstructed from the same committed journal as operational memory. */
export interface GraphState {
  objectives: Map<string, Stored<'objective'>>
  capabilities: Map<string, Capability>
  paths: Map<string, Path>
  coveragePlans: Map<string, Stored<'coverage-plan'>>
}
/** Evaluated state at a specific time and access context; confidence is evidence confidence, never success probability. */
export interface GraphEvaluation {
  state: 'active' | 'conditional' | 'unknown' | 'blocked' | 'needs-revalidation'
  assurance: 'observed' | 'validated'
  reasons: string[]
  capabilityIds: string[]
  evidenceIds: string[]
  confidence: number
  needsRevalidation: boolean
}
/** Create independent graph projections.
 * @returns empty objective, capability, path and coverage collections.
 */
export function emptyGraph(): GraphState {
  return { objectives: new Map(), capabilities: new Map(), paths: new Map(), coveragePlans: new Map() }
}

function supported(state: MemoryState, assetId: AssetId): boolean {
  return state.assetFacts.get(assetId)?.some(id => !state.retracted.has(id)) ?? false
}
function requireAssets(state: MemoryState, ids: readonly AssetId[]): void {
  if (ids.some(id => !supported(state, id))) throw new MemoryError('MEMORY_REFERENCE',
    'Graph records require supported asset identities; query current assets first.')
}
function requireContext(state: MemoryState, event: MemoryEvent, context: AttemptContext): void {
  if (digest(state.bindings.get(event.sessionId)?.context) !== digest(context)) throw new MemoryError('MEMORY_BINDING',
    'Graph context must match the bound session; begin another session for different access conditions.')
}
function capabilityOf(state: MemoryState, id: string): Capability {
  const capability = state.capabilities.get(id)
  if (!capability) throw new MemoryError('MEMORY_REFERENCE', 'Capability is unavailable; query current capabilities first.')
  return capability
}
function boundContext(state: MemoryState, sessionId: string): AttemptContext {
  const binding = state.bindings.get(sessionId)
  if (!binding) throw new MemoryError('MEMORY_BINDING', 'Graph records require a bound initiating session.')
  return binding.context
}
function revise(existing: { revision: number } | undefined, expected: number): number {
  if ((existing?.revision ?? 0) !== expected) throw new MemoryError('MEMORY_CONFLICT',
    'Graph record changed; query its current revision before updating it.')
  return expected + 1
}
function validateAttempt(state: MemoryState, capability: Input<'capability'>, event: MemoryEvent): void {
  if (!capability.verificationAttemptId) return
  const attempt = state.attempts.get(capability.verificationAttemptId)
  if (!attempt || attempt.outcome !== 'completed' || attempt.conclusion !== 'confirmed'
    || attempt.assessmentId !== event.assessmentId || attempt.method !== capability.validationMethod
    || attempt.configurationFingerprint !== capability.configurationFingerprint
    || digest(attempt.context) !== digest(capability.context)
    || ![capability.source, capability.target].every(id => attempt.assetIds.includes(id))
    || Date.parse(attempt.applicableUntil) <= Date.parse(event.time)
    || Date.parse(attempt.evidence.observedAt) > Date.parse(event.time)
    || Date.parse(attempt.evidence.observedAt) < Date.parse(capability.evidence.observedAt)
    || attempt.assetIds.some(id => attempt.assetSignatures[id] !== assetSignature(state, id))) throw new MemoryError('MEMORY_REFERENCE',
    'Capability validation requires a current completed confirmed attempt, matching context and endpoint assets, after the capability evidence, with unchanged supporting observations.')
}

/** Apply graph commands to a private projection; dependent work is generated by reconcileGraph.
 * @param state - disposable candidate with the journal's already projected observations and attempts.
 * @param event - transaction whose time is used for deterministic validation.
 */
export function projectGraph(state: MemoryState, event: MemoryEvent): void {
  const input = event.payload
  const metadata = { assessmentId: event.assessmentId, sessionId: event.sessionId,
    recordedAt: event.time, evidenceId: event.id }
  switch (input.kind) {
    case 'objective': {
      requireAssets(state, [input.businessServiceId, ...input.assetIds])
      const serviceFacts = state.assetFacts.get(input.businessServiceId) ?? []
      if (!serviceFacts.some(id => !state.retracted.has(id)
        && state.facts.get(id)?.observation.kind === 'business-service')) throw new MemoryError('MEMORY_REFERENCE',
        'An objective must reference an observed business-service asset.')
      state.objectives.set(input.id, { ...input, ...metadata,
        revision: revise(state.objectives.get(input.id), input.expectedRevision) })
      break
    }
    case 'capability': {
      requireAssets(state, [input.source, input.target])
      requireContext(state, event, input.context)
      if (input.source === input.target || new Set(input.requires).size !== input.requires.length
        || new Set(input.conditions.map(condition => condition.id)).size !== input.conditions.length) throw new MemoryError('MEMORY_REFERENCE',
        'Capabilities require distinct endpoints, prerequisite ids and condition ids.')
      if (Date.parse(input.validUntil) <= Date.parse(input.validFrom) || Date.parse(input.evidence.observedAt) < Date.parse(input.validFrom)
        || Date.parse(input.evidence.observedAt) >= Date.parse(input.validUntil) || Date.parse(input.evidence.observedAt) > Date.parse(event.time)) throw new MemoryError('MEMORY_REFERENCE',
        'Capability evidence must fall in a nonempty validity interval and cannot come from the future.')
      const support = input.supportObservationIds.map(id => state.facts.get(id))
      if (support.some(fact => !fact || state.retracted.has(fact.id) || fact.observation.basis !== 'observed'
        || Date.parse(fact.observedAt) > Date.parse(event.time) || digest(fact.observation) !== assetSignature(state, fact.assetId))) throw new MemoryError('MEMORY_REFERENCE',
        'Capability support must reference current observed facts; inferred, retracted or superseded assertions cannot establish access.')
      const reaches = (id: string): boolean => {
        const pending = [id], seen = new Set<string>()
        while (pending.length) {
          const next = pending.pop()
          if (next === undefined) break
          if (next === input.id) return true
          if (seen.has(next)) continue
          seen.add(next)
          pending.push(...(state.capabilities.get(next)?.requires ?? []))
        }
        return false
      }
      if (input.requires.some(id => !state.capabilities.has(id) || reaches(id))) throw new MemoryError('MEMORY_REFERENCE',
        'Capability prerequisites must exist and cannot form a dependency cycle.')
      if (input.verificationAttemptId && (input.state !== 'available'
        || input.conditions.some(condition => condition.satisfied !== true))) throw new MemoryError('MEMORY_REFERENCE',
        'A blocked, unknown or conditional capability cannot be promoted to validated.')
      validateAttempt(state, input, event)
      const assetIds = [...new Set([input.source, input.target, ...support.flatMap(fact => fact ? [fact.assetId] : [])])]
      state.capabilities.set(input.id, { ...input, ...metadata,
        revision: revise(state.capabilities.get(input.id), input.expectedRevision),
        supportAssetIds: assetIds,
        assetSignatures: Object.fromEntries(assetIds.map(id => [id, assetSignature(state, id)])),
        requiredRevisions: Object.fromEntries(input.requires.map(id => [id, capabilityOf(state, id).revision])) })
      break
    }
    case 'path': {
      requireAssets(state, [input.entry, input.target])
      const objective = state.objectives.get(input.objectiveId)
      if (!objective || !objective.assetIds.includes(input.target)) throw new MemoryError('MEMORY_REFERENCE',
        'A path target must belong to its recorded business objective.')
      const visited = new Set<AssetId>([input.entry])
      let cursor = input.entry
      for (const id of input.capabilityIds) {
        const capability = state.capabilities.get(id)
        if (!capability || capability.source !== cursor || visited.has(capability.target)) throw new MemoryError('MEMORY_REFERENCE',
          'A path must be a contiguous directed chain without repeated assets.')
        requireContext(state, event, capability.context)
        cursor = capability.target
        visited.add(cursor)
      }
      if (cursor !== input.target) throw new MemoryError('MEMORY_REFERENCE', 'The capability chain must end at the path target.')
      state.paths.set(input.id, { ...input, ...metadata, revision: revise(state.paths.get(input.id), input.expectedRevision),
        objectiveRevision: objective.revision,
        capabilityRevisions: Object.fromEntries(input.capabilityIds.map(id => [id, capabilityOf(state, id).revision])) })
      break
    }
    case 'coverage-plan':
      requireAssets(state, input.assetIds)
      requireContext(state, event, input.context)
      if (!state.objectives.has(input.objectiveId)) throw new MemoryError('MEMORY_REFERENCE',
        'Coverage needs an existing business objective.')
      state.coveragePlans.set(input.id, { ...input, ...metadata,
        revision: revise(state.coveragePlans.get(input.id), input.expectedRevision) })
      break
    default:
      // This projection receives only graph commands from the journal owner.
      break
  }
}

function conclude(reasons: string[], capabilities: Capability[], evidenceIds: string[], confidence: number): GraphEvaluation {
  const needsRevalidation = reasons.some(reason => /^(expired|not-yet-valid|support|revision|context|objective|validation):/.test(reason))
  const state = reasons.some(reason => reason.startsWith('blocked:')) ? 'blocked'
    : needsRevalidation ? 'needs-revalidation'
      : reasons.some(reason => reason.startsWith('unknown:')) ? 'unknown'
        : reasons.length ? 'conditional' : 'active'
  return { state, needsRevalidation, assurance: state === 'active' && capabilities.every(capability => capability.verificationAttemptId)
    ? 'validated' : 'observed', reasons: [...new Set(reasons)].sort(), capabilityIds: capabilities.map(capability => capability.id),
  evidenceIds: [...new Set(evidenceIds)], confidence }
}

/** Evaluate a capability and the AND of all its prerequisites without executing any action.
 * @param state - committed projection.
 * @param id - recorded capability identity.
 * @param at - UTC evaluation timestamp, independent of replay time.
 * @param context - session access conditions; a mismatch requires revalidation.
 * @param budget - shared search budget when present; absence evaluates the full recorded prerequisite closure.
 * @returns explainable state, prerequisite closure and supporting evidence ids.
 */
export function evaluateCapability(state: MemoryState, id: string, at: string, context: AttemptContext,
  budget?: EvaluationBudget): GraphEvaluation {
  const capabilities: Capability[] = [], reasons: string[] = [], evidenceIds: string[] = []
  const visited = new Set<string>()
  let confidence = 1
  const pending = [id]
  while (pending.length) {
    const key = pending.pop()
    if (key === undefined) break
    if (visited.has(key)) continue
    if (budget) {
      if (budget.remaining <= 0) {
        budget.exhausted = true; confidence = 0
        reasons.push(`unknown:${key}:evaluation-budget-exhausted`)
        break
      }
      budget.remaining--
    }
    visited.add(key)
    const capability = state.capabilities.get(key)
    if (!capability) { confidence = 0; reasons.push(`unknown:${key}:missing-capability`); continue }
    capabilities.push(capability); evidenceIds.push(capability.evidenceId)
    if (digest(capability.context) !== digest(context)) reasons.push(`context:${key}:access-conditions-changed`)
    if (Date.parse(at) < Date.parse(capability.validFrom)) reasons.push(`not-yet-valid:${key}`)
    if (Date.parse(at) >= Date.parse(capability.validUntil)) reasons.push(`expired:${key}`)
    if (capability.state !== 'available') reasons.push(`${capability.state}:${key}`)
    for (const condition of capability.conditions) if (condition.satisfied !== true) reasons.push(
      `${condition.satisfied === null ? 'unknown' : 'condition'}:${key}:${condition.id}`)
    for (const assetId of capability.supportAssetIds) {
      if (capability.assetSignatures[assetId] !== assetSignature(state, assetId)) reasons.push(`support:${key}:asset-changed:${assetId}`)
    }
    for (const factId of capability.supportObservationIds) {
      const fact = state.facts.get(factId)
      if (!fact || state.retracted.has(factId)) reasons.push(`support:${key}:assertion-retracted:${factId}`)
      else { evidenceIds.push(fact.evidenceId); confidence = Math.min(confidence, fact.observation.confidence) }
    }
    if (capability.verificationAttemptId) {
      const attempt = state.attempts.get(capability.verificationAttemptId)
      if (!attempt || Date.parse(attempt.applicableUntil) <= Date.parse(at)) reasons.push(`validation:${key}:attempt-expired`)
      else {
        evidenceIds.push(attempt.evidenceId)
        if (attempt.assetIds.some(id => attempt.assetSignatures[id] !== assetSignature(state, id))) reasons.push(`validation:${key}:attempt-support-changed`)
      }
    }
    for (const required of capability.requires) {
      if (state.capabilities.get(required)?.revision !== capability.requiredRevisions[required]) reasons.push(`revision:${key}:prerequisite-changed:${required}`)
    }
    pending.push(...[...capability.requires].reverse())
  }
  return conclude(reasons, capabilities, evidenceIds, confidence)
}

function evaluateChain(state: MemoryState, ids: string[], entry: AssetId, at: string, context: AttemptContext,
  budget?: EvaluationBudget): GraphEvaluation {
  const cache = new Map<string, GraphEvaluation>()
  const evaluate = (id: string) => {
    const existing = cache.get(id)
    if (existing) return existing
    const result = evaluateCapability(state, id, at, context, budget)
    cache.set(id, result)
    return result
  }
  const evaluations = ids.map(evaluate)
  const reasons = evaluations.flatMap(value => value.reasons)
  const reached = new Set([entry]), examined = new Set<string>()
  // Prerequisites are AND branches. Their source must be reached before their capability can contribute control.
  for (const id of ids) {
    const pending = [{ id, expanded: false }]
    while (pending.length) {
      if (budget?.exhausted) break
      const next = pending.pop()
      if (!next || examined.has(next.id)) continue
      const capability = capabilityOf(state, next.id)
      if (!next.expanded) {
        pending.push({ id: next.id, expanded: true }, ...[...capability.requires].reverse().map(id => ({ id, expanded: false })))
        continue
      }
      examined.add(next.id)
      if (!reached.has(capability.source)) reasons.push(`unknown:${next.id}:prerequisite-source-unreached`)
      else if (evaluate(next.id).state === 'active') reached.add(capability.target)
    }
  }
  const closure = [...new Set(evaluations.flatMap(value => value.capabilityIds))]
  return conclude(reasons, closure.map(id => capabilityOf(state, id)), evaluations.flatMap(value => value.evidenceIds),
    Math.min(...evaluations.map(value => value.confidence)))
}

/** Evaluate an explicit path, including off-path prerequisites and pinned objective/capability revisions.
 * @param state - committed business projection.
 * @param path - previously recorded contiguous chain.
 * @param at - current UTC timestamp.
 * @param context - requesting session's access conditions.
 * @returns explainable path state; validation never establishes destination authorization.
 */
export function evaluatePath(state: MemoryState, path: Path, at: string, context: AttemptContext): GraphEvaluation {
  const evaluation = evaluateChain(state, path.capabilityIds, path.entry, at, context)
  const reasons = [...evaluation.reasons]
  const objective = state.objectives.get(path.objectiveId)
  if (objective?.revision !== path.objectiveRevision) reasons.push(`objective:${path.objectiveId}:revision-changed`)
  if (objective && [objective.businessServiceId, ...objective.assetIds].some(id => !supported(state, id))) reasons.push(`objective:${path.objectiveId}:asset-unavailable`)
  for (const id of path.capabilityIds) if (state.capabilities.get(id)?.revision !== path.capabilityRevisions[id]) reasons.push(`revision:${id}:path-step-changed`)
  return conclude(reasons, evaluation.capabilityIds.map(id => capabilityOf(state, id)),
    [path.evidenceId, ...evaluation.evidenceIds], evaluation.confidence)
}

/** Generate durable retest work in the same transaction that invalidates a recorded path or capability.
 * @param state - candidate projection after its next journal operation.
 * @param event - deterministic evaluation time and assessment for new work.
 */
export function reconcileGraph(state: MemoryState, event: MemoryEvent): void {
  if (!state.capabilities.size) return
  const candidates = [
    ...[...state.capabilities.values()].map(value => ({ value, assetIds: [value.source, value.target],
      result: evaluateCapability(state, value.id, event.time, value.context) })),
    ...[...state.paths.values()].map(value => ({ value, assetIds: [value.entry, value.target],
      result: evaluatePath(state, value, event.time, boundContext(state, value.sessionId)) })),
  ]
  for (const { value, assetIds, result } of candidates) {
    if (!result.needsRevalidation) continue
    const supportRevision = result.capabilityIds.map((id) => {
      const capability = capabilityOf(state, id)
      return [id, capability.revision,
        capability.supportAssetIds.map(assetId => [assetId, assetSignature(state, assetId)]),
        capability.supportObservationIds.map(id => [id, state.retracted.has(id)])]
    })
    const objectiveRevision = value.kind === 'path' ? state.objectives.get(value.objectiveId)?.revision : null
    const id = `retest:${digest([value.kind, value.id, value.revision, result.reasons, supportRevision, objectiveRevision])}`
    if (!state.tasks.has(id)) state.tasks.set(id, { id, title: `Revalidate ${value.kind}: ${value.id}`,
      reason: JSON.stringify({ recordKind: value.kind, recordId: value.id, reasons: result.reasons }), assetIds,
      prerequisites: [], priority: 'high', retryWhen: 'New evidence and a matching completed attempt support the affected assumptions.',
      stopWhen: 'The graph assertion is deliberately updated or rejected with evidence.', revision: 1, status: 'pending',
      assessmentId: event.assessmentId })
  }
}

/** Expand planned coverage into independently attributable asset/test/context cells.
 * @param state - committed business projection.
 * @param at - current UTC timestamp for applicability checks.
 * @returns cells retaining all matching attempts, current applicability and explicit unknown coverage.
 */
export function coverageMatrix(state: MemoryState, at: string): object[] {
  return [...state.coveragePlans.values()].flatMap(plan => plan.assetIds.map((assetId) => {
    const attempts = [...state.attempts.values()].filter(attempt => attempt.assetIds.includes(assetId)
      && attempt.method === plan.method && digest(attempt.context) === digest(plan.context)
      && attempt.configurationFingerprint === plan.configurationFingerprint).sort((a, b) => b.sequence - a.sequence)
    const attempt = attempts[0]
    const stale = attempt !== undefined && (Date.parse(attempt.applicableUntil) <= Date.parse(at)
      || attempt.assetIds.some(id => attempt.assetSignatures[id] !== assetSignature(state, id)))
    const status = !supported(state, assetId) ? 'asset-unavailable' : !attempt ? 'untested' : stale ? 'needs-revalidation'
      : attempt.outcome === 'completed' ? attempt.conclusion : attempt.outcome
    return { planId: plan.id, assetId, objectiveId: plan.objectiveId, method: plan.method, context: plan.context,
      configurationFingerprint: plan.configurationFingerprint, status,
      latestAttemptId: attempt?.id ?? null, attemptIds: attempts.map(value => value.id),
      assessmentId: attempt?.assessmentId ?? null, authorization: 'external scope policy',
      interpretation: 'A not-reproduced result applies only to this test, access context, configuration and validity period.' }
  }))
}

/** Search bounded simple capability chains; every prerequisite is evaluated even when it is off the chain.
 * @param state - committed graph.
 * @param entry - starting asset; this query does not establish control over it.
 * @param target - desired destination asset.
 * @param context - bound access conditions.
 * @param at - UTC evaluation time.
 * @param limits - operator-controlled depth, examined-edge and complete-path bounds.
 * @returns candidate chains, explicit truncation and explanations; an empty result never establishes absence of access.
 */
export function findPaths(state: MemoryState, entry: AssetId, target: AssetId, context: AttemptContext,
  at: string, limits: { depth: number; expansions: number; paths: number }): object {
  requireAssets(state, [entry, target])
  if (entry === target) throw new MemoryError('MEMORY_REFERENCE', 'Choose distinct entry and target assets.')
  const adjacency = new Map<AssetId, Capability[]>()
  for (const capability of [...state.capabilities.values()].sort((a, b) => a.id.localeCompare(b.id))) {
    const edges = adjacency.get(capability.source) ?? []
    edges.push(capability); adjacency.set(capability.source, edges)
  }
  const queue = [{ asset: entry, chain: [] as string[], visited: new Set([entry]) }]
  const paths: object[] = []
  const budget: EvaluationBudget = { remaining: limits.expansions, exhausted: false }
  let truncated = false
  search: while (queue.length) {
    const next = queue.shift()
    if (!next) break
    const edges = adjacency.get(next.asset) ?? []
    if (next.chain.length >= limits.depth) {
      if (edges.some(edge => !next.visited.has(edge.target))) truncated = true
      continue
    }
    for (const edge of edges) {
      if (budget.remaining <= 0) { truncated = true; break search }
      budget.remaining--
      if (next.visited.has(edge.target)) continue
      const chain = [...next.chain, edge.id]
      if (edge.target === target) {
        paths.push({ capabilityIds: chain, evaluation: evaluateChain(state, chain, entry, at, context, budget) })
        if (budget.exhausted) { truncated = true; break search }
        if (paths.length >= limits.paths) { truncated = true; break search }
      } else queue.push({ asset: edge.target, chain, visited: new Set([...next.visited, edge.target]) })
    }
  }
  return { entry, target, context, evaluatedAt: at, paths, expansions: limits.expansions - budget.remaining, truncated,
    assurance: 'Candidate chains require evidence review; validated steps are submitted assessment claims.',
    authorization: 'External scope policy remains authoritative; entry control and destination access are not granted.',
    coverage: 'An empty or truncated search does not establish that no attack path exists.' }
}
